CREATE TABLE Survey (
    Id INT IDENTITY(1,1) PRIMARY KEY,
    Title NVARCHAR(200) NOT NULL,
    Description NVARCHAR(MAX) NULL,
    IsActive BIT NOT NULL DEFAULT 1,
    CreatedAt DATETIME2 NOT NULL DEFAULT GETUTCDATE()
);

CREATE TABLE Question (
    Id INT IDENTITY(1,1) PRIMARY KEY,
    SurveyId INT NOT NULL FOREIGN KEY REFERENCES Survey(Id) ON DELETE CASCADE,
    Text NVARCHAR(MAX) NOT NULL,
    Type INT NOT NULL,
    [Order] INT NOT NULL DEFAULT 0
);

CREATE TABLE QuestionOption (
    Id INT IDENTITY(1,1) PRIMARY KEY,
    QuestionId INT NOT NULL FOREIGN KEY REFERENCES Question(Id) ON DELETE CASCADE,
    Value NVARCHAR(200) NOT NULL,
    Label NVARCHAR(200) NULL,
    [Order] INT NOT NULL DEFAULT 0
);

CREATE TABLE SurveyResponse (
    Id INT IDENTITY(1,1) PRIMARY KEY,
    SurveyId INT NOT NULL FOREIGN KEY REFERENCES Survey(Id) ON DELETE CASCADE,
    SubmittedAt DATETIME2 NOT NULL DEFAULT GETUTCDATE()
);

CREATE TABLE Answer (
    Id INT IDENTITY(1,1) PRIMARY KEY,
    SurveyResponseId INT NOT NULL FOREIGN KEY REFERENCES SurveyResponse(Id) ON DELETE CASCADE,
    QuestionId INT NOT NULL, -- No cascade delete here to avoid cycles, but it's safe if Survey cascades
    SelectedOptionId INT NULL FOREIGN KEY REFERENCES QuestionOption(Id),
    TextValue NVARCHAR(MAX) NULL
);
